"""Serve files from a directory.

The generic routes — pictures and the work_dir zip — come from
``cosmo_ecosystem.files_route.serve_files``, which takes the app's own job class and
pulls the files itself. Only the GPX route stays here: it is the target of the QR code and the
completion mail, and the framework has no counterpart for a domain file path.

``create_download_button`` is re-exported from the framework so the button and
the route it links to cannot drift apart — they are now defined in one place.
"""

import logging
import os

from cosmo_ecosystem import job_persistence
from cosmo_ecosystem.files_route import create_download_button as create_download_button
from cosmo_ecosystem.files_route import serve_files as _serve_framework_files
from flask import abort, send_file

from cosmonaut_app.constants.general import GPX_FILE
from cosmonaut_app.cosmonaut_job import CosmonautJob
from cosmonaut_app.error_handling import JobNotFound

log = logging.getLogger(__name__)


def serve_files(app):
    """Register the framework's file routes plus cosmonaut's GPX route."""
    _serve_framework_files(app, job_class=CosmonautJob)

    @app.server.route(f"/download/<job_id>/{GPX_FILE}")
    def download_gpx(job_id):
        """Serve GPX file for download."""
        log.debug(f"Serving GPX download for job_id={job_id}")

        # An unknown job id is a not-found, not a server error. The framework's
        # routes answer 404 themselves, but expose no hook a custom route
        # could reuse, so this route keeps its own.
        try:
            job = CosmonautJob(job_id)
        except JobNotFound:
            log.error(f"Job not found for job_id={job_id}")
            abort(404, description="Job not found")
        # Pull first: the pod serving a download is usually not the pod that
        # produced the file (e.g. a GPX regenerated by the reverse-route toggle).
        # One file, so the single-file pull, not the whole work dir.
        gpx_path = job_persistence.pull_file(job.job_id, GPX_FILE)

        if not os.path.exists(gpx_path):
            log.error(f"GPX file not found at {gpx_path}")
            abort(404, description="GPX file not found")

        return send_file(
            gpx_path,
            mimetype="application/gpx+xml",
            as_attachment=True,
            download_name=GPX_FILE,
        )
